@Injectable({ providedIn: 'root' })
export class I18nService {
  language = signal<Language>((localStorage.getItem('language') as Language) || 'ka');
  t(key: string) {
    return (
      phase3[this.language()][key] ||
      (messages[this.language()] as Record<string, string>)[key] ||
      phase3.en[key] ||
      (messages.en as Record<string, string>)[key] ||
      key
    );
  }
  set(value: Language) {
    this.language.set(value);
    localStorage.setItem('language', value);
  }
}
